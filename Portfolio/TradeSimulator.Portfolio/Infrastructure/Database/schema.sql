-- All timestamps are stored and returned in UTC; only the UI converts them to the local time zone.

CREATE TABLE IF NOT EXISTS events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stream_id UUID NOT NULL,
    event_type VARCHAR(100) NOT NULL,
    version INT NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    payload JSONB NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_events_stream_version
    ON events(stream_id, version);

-- Every appended asset event is queued here in the same transaction; the read model reacts to it.
CREATE TABLE IF NOT EXISTS event_outbox (
    position BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    routing_key TEXT NOT NULL,
    payload JSONB NOT NULL,
    traceparent TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    published_at TIMESTAMPTZ NULL
);

CREATE INDEX IF NOT EXISTS ix_event_outbox_pending_position
    ON event_outbox(position)
    WHERE published_at IS NULL;

-- Finds the asset that holds a reservation.
CREATE INDEX IF NOT EXISTS ix_events_reservation
    ON events ((payload->>'reservationId'))
    WHERE event_type = 'AssetBlocked';
