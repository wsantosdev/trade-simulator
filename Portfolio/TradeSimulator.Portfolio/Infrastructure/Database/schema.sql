-- All timestamps are stored and returned in UTC; only the UI converts them to the local time zone.

CREATE TABLE IF NOT EXISTS events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stream_id UUID NOT NULL,
    event_type VARCHAR(100) NOT NULL,
    version INT NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    payload JSONB NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_events_stream_version
    ON events(stream_id, version);

-- Only the latest snapshot of each asset is kept; it is written every 100 events.
CREATE TABLE IF NOT EXISTS snapshots (
    stream_id UUID PRIMARY KEY,
    version INT NOT NULL CHECK (version > 0),
    payload JSONB NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Write side: assets with Total > 0. Holds only the optimistic-concurrency version; the unique
-- (account_id, ticker) index guards concurrent first deposits. The row is deleted when the asset is emptied.
CREATE TABLE IF NOT EXISTS active_assets (
    asset_id UUID PRIMARY KEY,
    account_id UUID NOT NULL,
    ticker TEXT NOT NULL,
    version INT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

-- Read models live in MongoDB (see PATTERNS.md); the event store has none.
DROP TABLE IF EXISTS asset_read_model;

CREATE UNIQUE INDEX IF NOT EXISTS ux_active_assets_account_ticker
    ON active_assets(account_id, ticker);

CREATE TABLE IF NOT EXISTS event_outbox (
    position BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    routing_key TEXT NOT NULL,
    payload JSONB NOT NULL,
    published_at TIMESTAMPTZ NULL
);

-- Durable idempotency guard: an envelope can change state only once, even if the Redis key is lost.
ALTER TABLE event_outbox ADD COLUMN IF NOT EXISTS envelope_id UUID NULL;

CREATE UNIQUE INDEX IF NOT EXISTS ux_event_outbox_envelope
    ON event_outbox(envelope_id)
    WHERE envelope_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS ix_event_outbox_pending_position
    ON event_outbox(position)
    WHERE published_at IS NULL;

-- Exchange of the outbox row (null = the portfolio events exchange).
ALTER TABLE event_outbox ADD COLUMN IF NOT EXISTS exchange TEXT NULL;

ALTER TABLE event_outbox ADD COLUMN IF NOT EXISTS traceparent TEXT NULL;

ALTER TABLE event_outbox ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT now();

-- Custody of each sell order: written in the same transaction as the asset events that block the quantity.
CREATE TABLE IF NOT EXISTS order_reservations (
    order_id UUID NOT NULL,
    account_id UUID NOT NULL,
    ticker TEXT NOT NULL,
    blocked BIGINT NOT NULL,
    remaining BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at TIMESTAMPTZ NULL,
    CONSTRAINT order_reservations_pkey PRIMARY KEY (order_id)
);

-- Exchange events already applied (idempotency, in the same transaction as their effects).
CREATE TABLE IF NOT EXISTS processed_order_events (
    envelope_id UUID NOT NULL,
    processed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT processed_order_events_pkey PRIMARY KEY (envelope_id)
);
