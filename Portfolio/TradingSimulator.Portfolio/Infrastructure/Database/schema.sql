CREATE TABLE IF NOT EXISTS asset_events (
    position BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id UUID NOT NULL,
    sequence INT NOT NULL,
    event_type TEXT NOT NULL,
    payload JSONB NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_asset_events_asset_sequence
    ON asset_events(asset_id, sequence);

-- Only the latest snapshot of each asset is kept; it is written every 100 events.
CREATE TABLE IF NOT EXISTS asset_snapshots (
    asset_id UUID PRIMARY KEY,
    version INT NOT NULL,
    payload JSONB NOT NULL
);

-- Write side: assets with Total > 0. Holds only the optimistic-concurrency version; the unique
-- (account_id, ticker) index guards concurrent first deposits. The row is deleted when the asset is emptied.
CREATE TABLE IF NOT EXISTS active_assets (
    asset_id UUID PRIMARY KEY,
    account_id UUID NOT NULL,
    ticker TEXT NOT NULL,
    version INT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

-- Read side (CQRS): projection of the asset events, written in the same transaction as the events.
CREATE TABLE IF NOT EXISTS asset_read_model (
    asset_id UUID PRIMARY KEY,
    account_id UUID NOT NULL,
    ticker TEXT NOT NULL,
    available BIGINT NOT NULL,
    blocked BIGINT NOT NULL,
    total BIGINT GENERATED ALWAYS AS (available + blocked) STORED
);

CREATE INDEX IF NOT EXISTS ix_asset_read_model_account ON asset_read_model(account_id, ticker);

-- Migrates databases created before the read model existed.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
               WHERE table_schema = current_schema() AND table_name = 'active_assets' AND column_name = 'available') THEN
        INSERT INTO asset_read_model (asset_id, account_id, ticker, available, blocked)
        SELECT asset_id, account_id, ticker, available, blocked FROM active_assets
        ON CONFLICT (asset_id) DO NOTHING;
        ALTER TABLE active_assets DROP COLUMN total, DROP COLUMN available, DROP COLUMN blocked;
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS ux_active_assets_account_ticker
    ON active_assets(account_id, ticker);

CREATE TABLE IF NOT EXISTS portfolio_outbox (
    position BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    routing_key TEXT NOT NULL,
    payload JSONB NOT NULL,
    published_at TIMESTAMPTZ NULL
);

-- Durable idempotency guard: an envelope can change state only once, even if the Redis key is lost.
ALTER TABLE portfolio_outbox ADD COLUMN IF NOT EXISTS envelope_id UUID NULL;

CREATE UNIQUE INDEX IF NOT EXISTS ux_portfolio_outbox_envelope
    ON portfolio_outbox(envelope_id)
    WHERE envelope_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS ix_portfolio_outbox_pending_position
    ON portfolio_outbox(position)
    WHERE published_at IS NULL;

-- Exchange of the outbox row (null = the portfolio events exchange).
ALTER TABLE portfolio_outbox ADD COLUMN IF NOT EXISTS exchange TEXT NULL;

ALTER TABLE portfolio_outbox ADD COLUMN IF NOT EXISTS traceparent TEXT NULL;

ALTER TABLE portfolio_outbox ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT now();

-- Custody of each sell order: written in the same transaction as the asset events that block the quantity.
CREATE TABLE IF NOT EXISTS order_reservations (
    order_id UUID NOT NULL,
    account_id UUID NOT NULL,
    ticker TEXT NOT NULL,
    blocked BIGINT NOT NULL,
    remaining BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at TIMESTAMPTZ NULL,
    CONSTRAINT order_reservations_pkey PRIMARY KEY (order_id)
);

-- Exchange events already applied (idempotency, in the same transaction as their effects).
CREATE TABLE IF NOT EXISTS processed_order_events (
    envelope_id UUID NOT NULL,
    processed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT processed_order_events_pkey PRIMARY KEY (envelope_id)
);
