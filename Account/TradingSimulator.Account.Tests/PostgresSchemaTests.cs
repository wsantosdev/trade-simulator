using Xunit;
using TradingSimulator.Account.Infrastructure.Database;

namespace TradingSimulator.Account.Tests;

public sealed class PostgresSchemaTests
{
    [Fact]
    public void Embedded_schema_creates_postgres_event_outbox_and_snapshot_tables()
    {
        using var schemaStream = typeof(PostgresAccountStore).Assembly
            .GetManifestResourceStream("TradingSimulator.Account.Infrastructure.Database.schema.sql");

        Assert.NotNull(schemaStream);
        using var reader = new StreamReader(schemaStream);
        var schema = reader.ReadToEnd();

        Assert.Contains("account_events", schema);
        Assert.Contains("event_outbox", schema);
        Assert.Contains("account_snapshots", schema);
        Assert.Contains("order_reservations", schema);
        Assert.Contains("response_outbox", schema);
        Assert.Contains("processed_messages", schema);
        Assert.Contains("available_balance NUMERIC(18, 2)", schema);
        Assert.Contains("provisioned_balance NUMERIC(18, 2)", schema);
        Assert.Contains("JSONB", schema);
        Assert.Contains("GENERATED BY DEFAULT AS IDENTITY", schema);
        Assert.Contains("TIMESTAMPTZ", schema);
        Assert.Contains("ux_account_events_single_open", schema);
    }
}
