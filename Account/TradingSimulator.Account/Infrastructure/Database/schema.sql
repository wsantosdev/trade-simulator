CREATE TABLE IF NOT EXISTS account_events (
    position BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id UUID NOT NULL,
    event_type TEXT NOT NULL,
    payload JSONB NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_account_events_account_id_position
    ON account_events(account_id, position);

CREATE UNIQUE INDEX IF NOT EXISTS ux_account_events_single_open
    ON account_events(account_id)
    WHERE event_type = 'AccountOpened';

CREATE TABLE IF NOT EXISTS account_snapshots (
    account_id UUID PRIMARY KEY,
    position BIGINT NOT NULL REFERENCES account_events(position),
    available_balance NUMERIC(18, 2) NOT NULL CHECK (available_balance >= 0),
    provisioned_balance NUMERIC(18, 2) NOT NULL CHECK (provisioned_balance >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS event_outbox (
    position BIGINT PRIMARY KEY REFERENCES account_events(position),
    event_type TEXT NOT NULL,
    payload JSONB NOT NULL,
    published_at TIMESTAMPTZ NULL
);

CREATE INDEX IF NOT EXISTS ix_event_outbox_pending_position
    ON event_outbox(position)
    WHERE published_at IS NULL;

CREATE TABLE IF NOT EXISTS order_reservations (
    order_id UUID PRIMARY KEY,
    account_id UUID NOT NULL,
    reserved_amount NUMERIC(18, 2) NOT NULL CHECK (reserved_amount > 0),
    remaining_amount NUMERIC(18, 2) NOT NULL CHECK (remaining_amount >= 0 AND remaining_amount <= reserved_amount),
    closed_at TIMESTAMPTZ NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_order_reservations_account_id
    ON order_reservations(account_id);

CREATE TABLE IF NOT EXISTS ignored_orders (
    order_id UUID PRIMARY KEY,
    reason TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS processed_messages (
    envelope_id UUID PRIMARY KEY,
    processed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS response_outbox (
    position BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    routing_key TEXT NOT NULL,
    payload JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    published_at TIMESTAMPTZ NULL
);

CREATE INDEX IF NOT EXISTS ix_response_outbox_pending_position
    ON response_outbox(position)
    WHERE published_at IS NULL;
