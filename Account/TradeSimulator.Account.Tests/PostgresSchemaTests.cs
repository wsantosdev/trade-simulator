using Xunit;
using TradeSimulator.Account.Infrastructure.Database;

namespace TradeSimulator.Account.Tests;

public sealed class PostgresSchemaTests
{
    [Fact]
    public void Embedded_schema_creates_postgres_event_table()
    {
        using var schemaStream = typeof(PostgresAccountStore).Assembly
            .GetManifestResourceStream("TradeSimulator.Account.Infrastructure.Database.schema.sql");

        Assert.NotNull(schemaStream);
        using var reader = new StreamReader(schemaStream);
        var schema = reader.ReadToEnd();

        Assert.Contains("CREATE TABLE IF NOT EXISTS events", schema);
        Assert.Contains("JSONB", schema);
        Assert.Contains("GENERATED BY DEFAULT AS IDENTITY", schema);
        Assert.Contains("TIMESTAMPTZ", schema);
    }
}
