-- The event stream is the only state; balances and reservations are rebuilt by replaying it.
CREATE TABLE IF NOT EXISTS events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stream_id UUID NOT NULL,
    event_type VARCHAR(100) NOT NULL,
    version INT NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    payload JSONB NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_events_stream_version
    ON events(stream_id, version);

-- Finds the account that holds a reservation.
CREATE INDEX IF NOT EXISTS ix_events_reservation
    ON events ((payload->'reservationId'->>'guid'))
    WHERE event_type = 'FundsReserved';
