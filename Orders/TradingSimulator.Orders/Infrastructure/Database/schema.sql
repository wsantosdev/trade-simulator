CREATE TABLE IF NOT EXISTS order_events (
    position BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id UUID NOT NULL,
    event_type TEXT NOT NULL,
    payload JSONB NOT NULL,
    request_hash CHAR(64) NULL,
    occurred_at TIMESTAMPTZ NOT NULL
);

ALTER TABLE order_events ADD COLUMN IF NOT EXISTS sequence INT NOT NULL DEFAULT 1;

CREATE UNIQUE INDEX IF NOT EXISTS ux_order_events_order_sequence
    ON order_events(order_id, sequence);

CREATE INDEX IF NOT EXISTS ix_order_events_order_id_position
    ON order_events(order_id, position);

DROP INDEX IF EXISTS ux_order_events_single_sent;

CREATE UNIQUE INDEX IF NOT EXISTS ux_order_events_single_submitted
    ON order_events(order_id)
    WHERE event_type IN ('OrderSubmitted', 'OrderSent');

CREATE UNIQUE INDEX IF NOT EXISTS ux_order_events_request_hash
    ON order_events(request_hash)
    WHERE request_hash IS NOT NULL;

CREATE TABLE IF NOT EXISTS order_outbox (
    position BIGINT PRIMARY KEY REFERENCES order_events(position),
    event_type TEXT NOT NULL,
    payload JSONB NOT NULL,
    published_at TIMESTAMPTZ NULL
);

ALTER TABLE order_outbox ADD COLUMN IF NOT EXISTS traceparent TEXT NULL;

CREATE INDEX IF NOT EXISTS ix_order_outbox_pending_position
    ON order_outbox(position)
    WHERE published_at IS NULL;

CREATE TABLE IF NOT EXISTS order_read_model (
    order_id UUID PRIMARY KEY,
    account_id UUID NOT NULL,
    ticker TEXT NOT NULL,
    side TEXT NOT NULL,
    type TEXT NOT NULL,
    quantity BIGINT NOT NULL,
    price NUMERIC(28, 8) NULL,
    state TEXT NOT NULL,
    executed_quantity BIGINT NOT NULL,
    remaining_quantity BIGINT NOT NULL,
    average_price NUMERIC(28, 8) NULL,
    last_price NUMERIC(28, 8) NULL,
    last_trade_at TIMESTAMPTZ NULL,
    sent_at TIMESTAMPTZ NOT NULL,
    last_action_at TIMESTAMPTZ NOT NULL,
    version INT NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_order_read_model_account_last_action
    ON order_read_model(account_id, last_action_at);
